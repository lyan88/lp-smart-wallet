def age_text(seconds):
    seconds = max(0, int(seconds or 0))
    if seconds >= 86400:
        return "%dd" % (seconds // 86400)
    if seconds >= 3600:
        return "%dh" % (seconds // 3600)
    return "%dm" % max(1, seconds // 60)
